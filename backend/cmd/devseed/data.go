// ── типы данных сидера ───────────────────────────────────────────────────────

// bi — двуязычное поле (ru/tg), зеркалит web/lib/data.ts Bi.
type bi struct{ RU, TG string }

// link — ссылка в описании достижения ({label,url} в web/lib/data.ts Achievement.links).
type link struct{ Label, URL string }

// achievementSeed — достижение институции/сотрудника (web/lib/data.ts Achievement).
type achievementSeed struct {
	ID       string
	Title    bi
	Year     int
	Category string
	Desc     bi
	Links    []link
}

// staffSeed — сотрудник (web/lib/data.ts Person).
type staffSeed struct {
	ID           string
	InstID       int
	Name         bi
	RoleType     string
	RoleLabel    bi
	Subject      *bi
	Photo        string
	Exp          string
	Bio          bi
	Education    []bi
	Achievements []achievementSeed
	Email        *string
	Phone        *string
}

// galleryItemSeed — элемент галереи (web/lib/data.ts Institution.gallery[]).
type galleryItemSeed struct {
	URL   string
	Label *bi
}

// alumnusSeed — выпускник (web/lib/data.ts Alumnus).
type alumnusSeed struct {
	ID       string
	Name     bi
	Photo    string
	GradYear int
	Now      bi
}

// transportInfoSeed — развозка (web/lib/data.ts Institution.transportInfo).
type transportInfoSeed struct {
	Types []bi
	Areas []bi
	Cost  int
}

// socialsSeed — соцсети (web/lib/data.ts Institution.socials).
type socialsSeed struct {
	Instagram *string
	Telegram  *string
	Facebook  *string
}

// institutionSeed — институция (web/lib/data.ts Institution), type уже замаплен
// на бэкенд-словарь (cat_kg→kindergarten, cat_school→school, cat_center→center,
// cat_uni→university).
type institutionSeed struct {
	ID            int
	Name          bi
	Type          string
	Curriculum    []string
	Region        string
	City          bi
	Area          string
	Price         int
	Score         float64
	Rev           int
	Transport     bool
	Food          bool
	Ver           bool
	Status        string
	Age           string
	Tag           *bi
	CoverPhoto    string
	Gallery       []galleryItemSeed
	Founded       int
	Students      int
	Description   bi
	Achievements  []achievementSeed
	Alumni        []alumnusSeed
	Address       bi
	Phone         string
	Email         string
	Website       string
	Socials       *socialsSeed
	TransportInfo *transportInfoSeed
	Lat, Lng      float64
}

// newsSeed — новость (web/lib/data.ts NewsArticle).
type newsSeed struct {
	ID       string
	InstID   int
	Title    bi
	Category bi
	CoverURL string
	VideoURL *string
	Content  bi
	Tags     []bi
	Status   string
	Views    int
}

// strp — адрес переданной строки (для nullable-полей *string).
func strp(s string) *string { return &s }

